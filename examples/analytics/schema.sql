-- Fixture: analytics. Timestamps with ordering checks, JSONB, bounded
-- decimals, and composite unique keys.

DROP SCHEMA IF EXISTS analytics CASCADE;
CREATE SCHEMA analytics;

CREATE TYPE analytics.experiment_status AS ENUM ('draft', 'running', 'paused', 'finished');

CREATE TABLE analytics.apps (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(120) NOT NULL,
    slug       varchar(64) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT apps_slug_unique UNIQUE (slug)
);

CREATE TABLE analytics.users (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id      integer NOT NULL REFERENCES analytics.apps(id) ON DELETE CASCADE,
    external_id varchar(64) NOT NULL,
    country     varchar(64) NOT NULL,
    created_at  timestamptz NOT NULL,
    CONSTRAINT users_app_external_unique UNIQUE (app_id, external_id)
);

CREATE TABLE analytics.sessions (
    id               integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id          integer NOT NULL REFERENCES analytics.users(id) ON DELETE CASCADE,
    started_at       timestamptz NOT NULL,
    ended_at         timestamptz NOT NULL,
    duration_seconds integer NOT NULL CHECK (duration_seconds >= 0),
    CONSTRAINT sessions_ended_after_started CHECK (ended_at > started_at)
);

CREATE TABLE analytics.events (
    id          bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id  integer NOT NULL REFERENCES analytics.sessions(id) ON DELETE CASCADE,
    name        varchar(64) NOT NULL,
    properties  jsonb NOT NULL DEFAULT '{}'::jsonb,
    occurred_at timestamptz NOT NULL
);

CREATE TABLE analytics.page_views (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id integer NOT NULL REFERENCES analytics.sessions(id) ON DELETE CASCADE,
    url        varchar(512) NOT NULL,
    referrer   varchar(512),
    viewed_at  timestamptz NOT NULL
);

CREATE TABLE analytics.experiments (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id     integer NOT NULL REFERENCES analytics.apps(id) ON DELETE CASCADE,
    key        varchar(64) NOT NULL,
    name       varchar(160) NOT NULL,
    status     analytics.experiment_status NOT NULL,
    started_at timestamptz,
    CONSTRAINT experiments_key_unique UNIQUE (key)
);

CREATE TABLE analytics.variants (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id integer NOT NULL REFERENCES analytics.experiments(id) ON DELETE CASCADE,
    name          varchar(64) NOT NULL,
    weight        numeric(5, 4) NOT NULL CHECK (weight >= 0),
    CONSTRAINT variants_experiment_name_unique UNIQUE (experiment_id, name),
    CONSTRAINT variants_weight_max CHECK (weight <= 1)
);

CREATE TABLE analytics.assignments (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    experiment_id integer NOT NULL REFERENCES analytics.experiments(id) ON DELETE CASCADE,
    user_id       integer NOT NULL REFERENCES analytics.users(id) ON DELETE CASCADE,
    variant_id    integer NOT NULL REFERENCES analytics.variants(id) ON DELETE CASCADE,
    assigned_at   timestamptz NOT NULL
);

CREATE TABLE analytics.metrics (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    app_id      integer NOT NULL REFERENCES analytics.apps(id) ON DELETE CASCADE,
    name        varchar(64) NOT NULL,
    value       numeric(18, 6) NOT NULL CHECK (value >= 0),
    recorded_at timestamptz NOT NULL
);
