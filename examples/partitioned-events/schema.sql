CREATE TABLE part.audit (
    id      bigint GENERATED BY DEFAULT AS IDENTITY,
    kind    text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (id, kind)
) PARTITION BY LIST (kind);

CREATE TABLE part.audit_login PARTITION OF part.audit
    FOR VALUES IN ('login');
CREATE TABLE part.audit_purchase PARTITION OF part.audit
    FOR VALUES IN ('purchase');

CREATE TABLE part.metrics (
    id     bigint GENERATED BY DEFAULT AS IDENTITY,
    app_id integer NOT NULL,
    value  numeric(18, 4) NOT NULL,
    PRIMARY KEY (id, app_id)
) PARTITION BY HASH (app_id);

CREATE TABLE part.metrics_0 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 0);
CREATE TABLE part.metrics_1 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 1);
CREATE TABLE part.metrics_2 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 2);
CREATE TABLE part.metrics_3 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 3);
