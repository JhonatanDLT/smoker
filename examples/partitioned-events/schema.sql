-- Fixture: partitioned tables.
-- One range-partitioned table, one list-partitioned table and one
-- hash-partitioned table. smoker must generate into the parent and let
-- PostgreSQL route each row.

DROP SCHEMA IF EXISTS part CASCADE;
CREATE SCHEMA part;

CREATE TABLE part.events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at date NOT NULL,
    kind       varchar(32) NOT NULL,
    amount     numeric(12, 2) NOT NULL CHECK (amount >= 0),
    PRIMARY KEY (id, created_at)
) PARTITION BY RANGE (created_at);

CREATE TABLE part.events_2025_01 PARTITION OF part.events
    FOR VALUES FROM ('2025-01-01') TO ('2025-02-01');
CREATE TABLE part.events_2025_02 PARTITION OF part.events
    FOR VALUES FROM ('2025-02-01') TO ('2025-03-01');
CREATE TABLE part.events_2025_03 PARTITION OF part.events
    FOR VALUES FROM ('2025-03-01') TO ('2025-04-01');
CREATE TABLE part.events_2025_04 PARTITION OF part.events
    FOR VALUES FROM ('2025-04-01') TO ('2025-05-01');
CREATE TABLE part.events_2025_05 PARTITION OF part.events
    FOR VALUES FROM ('2025-05-01') TO ('2025-06-01');
CREATE TABLE part.events_2025_06 PARTITION OF part.events
    FOR VALUES FROM ('2025-06-01') TO ('2025-07-01');
CREATE TABLE part.events_2025_07 PARTITION OF part.events
    FOR VALUES FROM ('2025-07-01') TO ('2025-08-01');
CREATE TABLE part.events_2025_08 PARTITION OF part.events
    FOR VALUES FROM ('2025-08-01') TO ('2025-09-01');
CREATE TABLE part.events_2025_09 PARTITION OF part.events
    FOR VALUES FROM ('2025-09-01') TO ('2025-10-01');
CREATE TABLE part.events_2025_10 PARTITION OF part.events
    FOR VALUES FROM ('2025-10-01') TO ('2025-11-01');
CREATE TABLE part.events_2025_11 PARTITION OF part.events
    FOR VALUES FROM ('2025-11-01') TO ('2025-12-01');
CREATE TABLE part.events_2025_12 PARTITION OF part.events
    FOR VALUES FROM ('2025-12-01') TO ('2026-01-01');

CREATE TABLE part.audit (
    id      bigint GENERATED BY DEFAULT AS IDENTITY,
    kind    text NOT NULL,
    payload jsonb NOT NULL DEFAULT '{}'::jsonb,
    PRIMARY KEY (id, kind)
) PARTITION BY LIST (kind);

CREATE TABLE part.audit_login PARTITION OF part.audit
    FOR VALUES IN ('login');
CREATE TABLE part.audit_purchase PARTITION OF part.audit
    FOR VALUES IN ('purchase');

CREATE TABLE part.metrics (
    id     bigint GENERATED BY DEFAULT AS IDENTITY,
    app_id integer NOT NULL,
    value  numeric(18, 4) NOT NULL,
    PRIMARY KEY (id, app_id)
) PARTITION BY HASH (app_id);

CREATE TABLE part.metrics_0 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 0);
CREATE TABLE part.metrics_1 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 1);
CREATE TABLE part.metrics_2 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 2);
CREATE TABLE part.metrics_3 PARTITION OF part.metrics
    FOR VALUES WITH (MODULUS 4, REMAINDER 3);

-- Multi-column range partition key.
CREATE TABLE part.tenant_events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    tenant_id  integer NOT NULL,
    created_at date NOT NULL,
    amount     numeric(12, 2) NOT NULL CHECK (amount >= 0),
    PRIMARY KEY (id, tenant_id, created_at)
) PARTITION BY RANGE (tenant_id, created_at);

CREATE TABLE part.tenant_events_a PARTITION OF part.tenant_events
    FOR VALUES FROM (1, MINVALUE) TO (100, MINVALUE);
CREATE TABLE part.tenant_events_b PARTITION OF part.tenant_events
    FOR VALUES FROM (100, MINVALUE) TO (200, MINVALUE);

-- Sub-partitioning: range by month, then list by level.
CREATE TABLE part.logs (
    id         bigint GENERATED BY DEFAULT AS IDENTITY,
    created_at date NOT NULL,
    level      text NOT NULL,
    message    text,
    PRIMARY KEY (id, created_at, level)
) PARTITION BY RANGE (created_at);

CREATE TABLE part.logs_2025_01 PARTITION OF part.logs
    FOR VALUES FROM ('2025-01-01') TO ('2025-02-01')
    PARTITION BY LIST (level);
CREATE TABLE part.logs_2025_01_info PARTITION OF part.logs_2025_01
    FOR VALUES IN ('info');
CREATE TABLE part.logs_2025_01_error PARTITION OF part.logs_2025_01
    FOR VALUES IN ('error');

CREATE TABLE part.logs_2025_02 PARTITION OF part.logs
    FOR VALUES FROM ('2025-02-01') TO ('2025-03-01')
    PARTITION BY LIST (level);
CREATE TABLE part.logs_2025_02_info PARTITION OF part.logs_2025_02
    FOR VALUES IN ('info');
CREATE TABLE part.logs_2025_02_error PARTITION OF part.logs_2025_02
    FOR VALUES IN ('error');
