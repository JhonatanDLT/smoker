-- Fixture: e-commerce. Self-reference, derived column, unique truncation,
-- enums, nullability and multi-table foreign keys.

DROP SCHEMA IF EXISTS shop CASCADE;
CREATE SCHEMA shop;

CREATE TYPE shop.order_status AS ENUM ('cart', 'paid', 'shipped', 'delivered', 'cancelled');
CREATE TYPE shop.payment_method AS ENUM ('card', 'paypal', 'transfer', 'cash');

CREATE TABLE shop.categories (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    parent_id integer REFERENCES shop.categories(id),
    name      text NOT NULL,
    slug      varchar(80) NOT NULL,
    CONSTRAINT categories_slug_unique UNIQUE (slug)
);

CREATE TABLE shop.products (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id integer NOT NULL REFERENCES shop.categories(id),
    sku         varchar(32) NOT NULL,
    name        varchar(160) NOT NULL,
    price       numeric(10, 2) NOT NULL CHECK (price > 0),
    stock       integer NOT NULL DEFAULT 0 CHECK (stock >= 0),
    active      boolean NOT NULL DEFAULT true,
    CONSTRAINT products_sku_unique UNIQUE (sku)
);

CREATE TABLE shop.customers (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email      varchar(255) NOT NULL,
    full_name  varchar(120) NOT NULL,
    country    varchar(64) NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT customers_email_unique UNIQUE (email)
);

CREATE TABLE shop.orders (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id integer NOT NULL REFERENCES shop.customers(id),
    status      shop.order_status NOT NULL,
    placed_at   timestamptz NOT NULL,
    total       numeric(12, 2) NOT NULL CHECK (total >= 0)
);

CREATE TABLE shop.order_items (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id   integer NOT NULL REFERENCES shop.orders(id) ON DELETE CASCADE,
    product_id integer NOT NULL REFERENCES shop.products(id),
    quantity   integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price > 0),
    line_total numeric(12, 2) NOT NULL CHECK (line_total > 0),
    CONSTRAINT order_items_line_total CHECK (line_total = quantity * unit_price)
);

CREATE TABLE shop.payments (
    id      integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id integer NOT NULL REFERENCES shop.orders(id) ON DELETE CASCADE,
    method  shop.payment_method NOT NULL,
    amount  numeric(12, 2) NOT NULL CHECK (amount > 0),
    paid_at timestamptz NOT NULL
);

CREATE TABLE shop.shipments (
    id            integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    order_id      integer NOT NULL REFERENCES shop.orders(id) ON DELETE CASCADE,
    carrier       varchar(64) NOT NULL,
    tracking_code varchar(64) NOT NULL,
    shipped_at    timestamptz NOT NULL,
    delivered_at  timestamptz,
    CONSTRAINT shipments_tracking_unique UNIQUE (tracking_code),
    CONSTRAINT shipments_delivered_after_shipped
        CHECK (delivered_at IS NULL OR delivered_at > shipped_at)
);

CREATE TABLE shop.reviews (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  integer NOT NULL REFERENCES shop.products(id) ON DELETE CASCADE,
    customer_id integer NOT NULL REFERENCES shop.customers(id),
    rating      integer NOT NULL CHECK (rating >= 1),
    body        text,
    created_at  timestamptz NOT NULL,
    CONSTRAINT reviews_rating_max CHECK (rating <= 5)
);

CREATE TABLE shop.coupons (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        varchar(32) NOT NULL,
    percent_off numeric(5, 2) NOT NULL CHECK (percent_off >= 0),
    expires_at  timestamptz,
    CONSTRAINT coupons_code_unique UNIQUE (code),
    CONSTRAINT coupons_percent_max CHECK (percent_off <= 100)
);

CREATE TABLE shop.inventory_movements (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id integer NOT NULL REFERENCES shop.products(id) ON DELETE CASCADE,
    delta      integer NOT NULL,
    reason     varchar(80) NOT NULL,
    created_at timestamptz NOT NULL
);
