-- pgproof demo schema: a small SaaS billing system.
-- Ten tables, enums, checks, a self-reference, a trigger, and a derived column.

DROP SCHEMA IF EXISTS billing CASCADE;
CREATE SCHEMA billing;

CREATE TYPE billing.plan_tier AS ENUM ('free', 'pro', 'business');
CREATE TYPE billing.subscription_status AS ENUM ('trialing', 'active', 'past_due', 'canceled');
CREATE TYPE billing.invoice_status AS ENUM ('draft', 'open', 'paid', 'void');
CREATE TYPE billing.payment_method AS ENUM ('card', 'transfer', 'cash', 'other');

CREATE TABLE billing.accounts (
    id                integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name              text NOT NULL,
    tax_id            varchar(13),
    country           varchar(64) NOT NULL DEFAULT 'México',
    parent_account_id integer REFERENCES billing.accounts(id),
    created_at        timestamptz NOT NULL DEFAULT now(),
    updated_at        timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE billing.users (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES billing.accounts(id) ON DELETE CASCADE,
    email      varchar(255) NOT NULL,
    full_name  varchar(120) NOT NULL,
    created_at timestamptz NOT NULL DEFAULT now(),
    CONSTRAINT users_email_unique UNIQUE (email)
);

CREATE TABLE billing.plans (
    id     integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code   varchar(32) NOT NULL UNIQUE,
    tier   billing.plan_tier NOT NULL,
    price  numeric(12, 2) NOT NULL CHECK (price >= 0),
    active boolean NOT NULL DEFAULT true
);

CREATE TABLE billing.subscriptions (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer NOT NULL REFERENCES billing.accounts(id) ON DELETE CASCADE,
    plan_id    integer NOT NULL REFERENCES billing.plans(id),
    status     billing.subscription_status NOT NULL,
    started_at timestamptz NOT NULL,
    ends_at    timestamptz,
    CONSTRAINT subscriptions_dates_ordered CHECK (ends_at IS NULL OR ends_at > started_at)
);

CREATE TABLE billing.invoices (
    id              integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id      integer NOT NULL REFERENCES billing.accounts(id) ON DELETE CASCADE,
    subscription_id integer REFERENCES billing.subscriptions(id),
    status          billing.invoice_status NOT NULL,
    issued_at       date NOT NULL,
    due_at          date NOT NULL,
    total           numeric(12, 2) NOT NULL CHECK (total >= 0),
    CONSTRAINT invoices_due_after_issue CHECK (due_at >= issued_at)
);

CREATE TABLE billing.invoice_lines (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id  integer NOT NULL REFERENCES billing.invoices(id) ON DELETE CASCADE,
    description varchar(200) NOT NULL,
    quantity    integer NOT NULL CHECK (quantity > 0),
    unit_price  numeric(12, 2) NOT NULL CHECK (unit_price >= 0),
    amount      numeric(12, 2) NOT NULL CHECK (amount > 0),
    CONSTRAINT invoice_lines_amount_matches CHECK (amount = quantity * unit_price)
);

CREATE TABLE billing.payments (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id integer NOT NULL REFERENCES billing.invoices(id) ON DELETE CASCADE,
    amount     numeric(12, 2) NOT NULL CHECK (amount > 0),
    method     billing.payment_method NOT NULL,
    reference  varchar(64),
    paid_at    timestamptz NOT NULL
);

CREATE TABLE billing.refunds (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    payment_id integer NOT NULL REFERENCES billing.payments(id) ON DELETE CASCADE,
    amount     numeric(12, 2) NOT NULL CHECK (amount > 0),
    reason     varchar(200),
    created_at timestamptz NOT NULL
);

CREATE TABLE billing.events (
    id         bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id integer REFERENCES billing.accounts(id) ON DELETE CASCADE,
    kind       varchar(64) NOT NULL,
    payload    jsonb NOT NULL DEFAULT '{}'::jsonb,
    created_at timestamptz NOT NULL
);

CREATE TABLE billing.api_keys (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    integer NOT NULL REFERENCES billing.users(id) ON DELETE CASCADE,
    key_prefix varchar(16) NOT NULL,
    hashed_key varchar(128) NOT NULL,
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    CONSTRAINT api_keys_prefix_unique UNIQUE (key_prefix)
);

CREATE OR REPLACE FUNCTION billing.touch_updated_at()
RETURNS trigger
LANGUAGE plpgsql
AS $$
BEGIN
    NEW.updated_at := now();
    RETURN NEW;
END;
$$;

CREATE TRIGGER accounts_touch_updated_at
    BEFORE UPDATE ON billing.accounts
    FOR EACH ROW
    EXECUTE FUNCTION billing.touch_updated_at();
