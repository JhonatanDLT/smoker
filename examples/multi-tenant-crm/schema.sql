-- Fixture: multi-tenant CRM. Composite primary key, composite unique keys,
-- tenant-scoped foreign keys, enums and bounded integers.

DROP SCHEMA IF EXISTS crm CASCADE;
CREATE SCHEMA crm;

CREATE TYPE crm.plan_tier AS ENUM ('starter', 'growth', 'enterprise');
CREATE TYPE crm.user_role AS ENUM ('owner', 'admin', 'member', 'viewer');
CREATE TYPE crm.deal_stage AS ENUM ('lead', 'qualified', 'proposal', 'won', 'lost');
CREATE TYPE crm.activity_kind AS ENUM ('call', 'email', 'meeting', 'note');

CREATE TABLE crm.tenants (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name       varchar(120) NOT NULL,
    slug       varchar(64) NOT NULL,
    plan       crm.plan_tier NOT NULL,
    created_at timestamptz NOT NULL,
    CONSTRAINT tenants_slug_unique UNIQUE (slug)
);

CREATE TABLE crm.users (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    email      varchar(255) NOT NULL,
    role       crm.user_role NOT NULL,
    active     boolean NOT NULL DEFAULT true,
    created_at timestamptz NOT NULL,
    CONSTRAINT users_tenant_email_unique UNIQUE (tenant_id, email)
);

CREATE TABLE crm.companies (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    name       varchar(160) NOT NULL,
    domain     varchar(120),
    created_at timestamptz NOT NULL
);

CREATE TABLE crm.contacts (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    company_id integer REFERENCES crm.companies(id) ON DELETE SET NULL,
    email      varchar(255) NOT NULL,
    full_name  varchar(120) NOT NULL,
    phone      varchar(40),
    created_at timestamptz NOT NULL
);

CREATE TABLE crm.deals (
    id             integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id      integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    contact_id     integer NOT NULL REFERENCES crm.contacts(id),
    stage          crm.deal_stage NOT NULL,
    amount         numeric(12, 2) NOT NULL CHECK (amount >= 0),
    probability    integer NOT NULL CHECK (probability >= 0),
    expected_close date NOT NULL,
    CONSTRAINT deals_probability_max CHECK (probability <= 100)
);

CREATE TABLE crm.activities (
    id          integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id   integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    deal_id     integer REFERENCES crm.deals(id) ON DELETE CASCADE,
    kind        crm.activity_kind NOT NULL,
    happened_at timestamptz NOT NULL,
    notes       text
);

CREATE TABLE crm.tags (
    id        integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    name      varchar(64) NOT NULL,
    CONSTRAINT tags_tenant_name_unique UNIQUE (tenant_id, name)
);

CREATE TABLE crm.contact_tags (
    contact_id integer NOT NULL REFERENCES crm.contacts(id) ON DELETE CASCADE,
    tag_id     integer NOT NULL REFERENCES crm.tags(id) ON DELETE CASCADE,
    PRIMARY KEY (contact_id, tag_id)
);

CREATE TABLE crm.subscriptions (
    id         integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tenant_id  integer NOT NULL REFERENCES crm.tenants(id) ON DELETE CASCADE,
    plan       crm.plan_tier NOT NULL,
    seats      integer NOT NULL CHECK (seats > 0),
    started_at timestamptz NOT NULL,
    renews_at  timestamptz NOT NULL,
    CONSTRAINT subscriptions_renews_after_start CHECK (renews_at > started_at)
);
