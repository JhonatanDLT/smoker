from __future__ import annotations

import os
import subprocess
from decimal import Decimal
from pathlib import Path

import psycopg
import pytest
from typer.testing import CliRunner

from pgproof.adapters.postgres.serialization import sql_literal
from pgproof.cli import app

ROOT = Path(__file__).resolve().parents[1]
SCHEMA = ROOT / "examples/saas-billing/schema.sql"
DSN = os.environ.get("PGPROOF_TEST_DSN")


def test_sql_literals() -> None:
    assert sql_literal(None) == "NULL"
    assert sql_literal(True) == "TRUE"
    assert sql_literal(False) == "FALSE"
    assert sql_literal(Decimal("1.20")) == "1.20"
    assert sql_literal("O'Reilly") == "'O''Reilly'"
    assert sql_literal("line\nbreak") == "'line\nbreak'"


def test_generate_sql_from_a_dump_without_a_database(tmp_path: Path) -> None:
    out = tmp_path / "data.sql"
    result = CliRunner().invoke(
        app,
        [
            "generate",
            "--schema-file",
            str(SCHEMA),
            "--rows",
            "3",
            "--seed",
            "5",
            "--sql",
            str(out),
        ],
    )
    assert result.exit_code == 0, result.output
    text = out.read_text(encoding="utf-8")

    assert text.startswith("-- Generated by pgproof")
    assert "BEGIN;" in text
    assert "COMMIT;" in text
    assert "TRUNCATE" in text
    assert 'INSERT INTO "billing"."accounts"' in text
    assert 'INSERT INTO "billing"."invoice_lines"' in text


@pytest.mark.integration
@pytest.mark.skipif(not DSN, reason="PGPROOF_TEST_DSN is not set")
def test_sql_export_applies_and_preserves_foreign_keys(tmp_path: Path) -> None:
    assert DSN
    schema = "pgproof_sql_export"
    schema_sql = f"""
    DROP SCHEMA IF EXISTS {schema} CASCADE;
    CREATE SCHEMA {schema};
    SET search_path TO {schema};
    CREATE TABLE parents (
        id integer PRIMARY KEY,
        name text NOT NULL
    );
    CREATE TABLE children (
        id integer PRIMARY KEY,
        parent_id integer NOT NULL REFERENCES parents (id),
        note text
    );
    """
    schema_file = tmp_path / "schema.sql"
    schema_file.write_text(schema_sql, encoding="utf-8")
    data_file = tmp_path / "data.sql"

    result = CliRunner().invoke(
        app,
        [
            "generate",
            "--schema-file",
            str(schema_file),
            "--rows",
            "7",
            "--seed",
            "9",
            "--sql",
            str(data_file),
        ],
    )
    assert result.exit_code == 0, result.output

    subprocess.run(
        ["psql", DSN, "-q", "-v", "ON_ERROR_STOP=1", "-f", str(schema_file)],
        check=True,
        capture_output=True,
    )
    subprocess.run(
        ["psql", DSN, "-q", "-v", "ON_ERROR_STOP=1", "-f", str(data_file)],
        check=True,
        capture_output=True,
    )

    connection = psycopg.connect(DSN)
    try:
        parents = connection.execute(
            f'SELECT count(*) FROM "{schema}".parents'
        ).fetchone()[0]
        children = connection.execute(
            f'SELECT count(*) FROM "{schema}".children'
        ).fetchone()[0]
        orphans = connection.execute(
            f'SELECT count(*) FROM "{schema}".children c '
            f'LEFT JOIN "{schema}".parents p ON p.id = c.parent_id '
            "WHERE p.id IS NULL"
        ).fetchone()[0]
    finally:
        connection.close()

    assert parents == 7
    assert children == 7
    assert orphans == 0
