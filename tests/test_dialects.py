from __future__ import annotations

from pathlib import Path

import pytest

from pgproof.adapters.base import DatabaseAdapter
from pgproof.adapters.postgres.dialect import PostgresDialect
from pgproof.adapters.registry import (
    available_dialects,
    get_adapter,
    get_ddl_loader,
    get_dialect,
)
from pgproof.adapters.script import SqlFileWriter
from pgproof.core.dialect import Capabilities, SqlDialect
from pgproof.core.invariants import invariants_from_catalog
from pgproof.core.ir import Catalog, Column, Table
from pgproof.core.ports import DdlLoader


def make_catalog() -> Catalog:
    return Catalog(
        database="test",
        server_version="16",
        tables=[
            Table(
                schema="public",
                name="accounts",
                columns=[
                    Column("id", "integer", nullable=False),
                    Column("email", "text", nullable=False),
                ],
                primary_key=["id"],
            )
        ],
    )


def test_postgres_dialect_satisfies_the_port() -> None:
    dialect = PostgresDialect()

    assert isinstance(dialect, SqlDialect)
    assert dialect.name == "postgres"
    assert isinstance(dialect.capabilities, Capabilities)
    assert dialect.capabilities.exclusion_constraints is True
    assert dialect.capabilities.row_identity == "ctid"


def test_registry_returns_a_dialect_and_a_ddl_loader() -> None:
    assert "postgres" in available_dialects()
    assert get_dialect("postgres").name == "postgres"
    assert isinstance(get_ddl_loader("postgres"), DdlLoader)
    adapter = get_adapter("postgres")
    assert isinstance(adapter, DatabaseAdapter)
    assert adapter.name == "postgres"
    assert adapter.dialect.name == "postgres"


def test_unknown_dialect_fails_with_the_available_list() -> None:
    with pytest.raises(ValueError, match="available"):
        get_dialect("oracle")


def test_invariants_use_the_injected_dialect() -> None:
    class RecordingDialect(PostgresDialect):
        def not_null_sql(self, table, column):  # type: ignore[no-untyped-def]
            return f"SELECT 'not-null:{table.key}.{column.name}'"

    invariants = invariants_from_catalog(make_catalog(), RecordingDialect())
    not_null = next(
        item for item in invariants if item.kind.value == "not_null"
    )

    assert not_null.violation_sql == "SELECT 'not-null:public.accounts.id'"


def test_dialect_wraps_count_and_sample_queries() -> None:
    dialect = PostgresDialect()

    assert dialect.count_sql("SELECT 1") == "SELECT count(*) FROM (SELECT 1) AS violations"
    assert (
        dialect.sample_sql("SELECT 1", 5)
        == "SELECT * FROM (SELECT 1) AS violations LIMIT 5"
    )


def test_sql_script_writer_uses_the_dialect(tmp_path: Path) -> None:
    catalog = make_catalog()
    table = catalog.table("public.accounts")
    out = tmp_path / "data.sql"
    writer = SqlFileWriter(out, PostgresDialect(), truncate=False)
    try:
        writer.write(table, iter([(1, "a@example.com")]))
        writer.commit()
    finally:
        writer.close()
    text = out.read_text(encoding="utf-8")

    assert text.startswith("-- Generated by pgproof")
    assert "BEGIN;" in text
    assert 'INSERT INTO "public"."accounts" ("id", "email") VALUES' in text
    assert "COMMIT;" in text
