"""Markdown renderer for a schema audit."""

from __future__ import annotations

from ...core.audit import Audit


class AuditMarkdownRenderer:
    extension = "md"

    def render(self, audit: Audit) -> str:
        lines = [
            f"# Schema readiness audit — {audit.database}",
            "",
            f"{audit.dialect} {audit.server_version} · verdict: **{audit.verdict}**",
            "",
            "## Inventory",
            "",
            (
                "| Tables | Columns | Foreign keys | Checks | Triggers | "
                "Functions | Procedures |"
            ),
            "|---:|---:|---:|---:|---:|---:|---:|",
            (
                f"| {audit.tables} | {audit.columns} | {audit.foreign_keys} | "
                f"{audit.checks} | {audit.triggers} | {audit.functions} | "
                f"{audit.procedures} |"
            ),
            "",
            "## What pgproof would verify",
            "",
            "| Invariant | Count |",
            "|---|---:|",
        ]
        for kind, count in sorted(audit.invariants.items()):
            lines.append(f"| `{kind}` | {count} |")
        lines.extend(["", "## Risks", ""])

        if not audit.risks:
            lines.append("No structural risks found.")
        else:
            lines.extend(
                ["| Severity | Table | Finding |", "|---|---|---|"]
            )
            order = {"high": 0, "medium": 1, "low": 2}
            for risk in sorted(audit.risks, key=lambda item: (order[item.severity], item.table)):
                lines.append(
                    f"| {risk.severity.upper()} | `{risk.table}` | {risk.finding} |"
                )

        lines.extend(
            [
                "",
                "## Next step",
                "",
                (
                    "A two-week pilot turns this inventory into a dataset that loads and a "
                    "report that proves it:"
                ),
                "",
                "1. Agree on three to five business invariants.",
                "2. Generate a synthetic dataset for staging.",
                "3. Repair what can be repaired and verify the rest.",
                "4. Leave a report and a runbook the team can rerun.",
                "",
                "_Generated by pgproof. No production rows were read to build this audit._",
                "",
            ]
        )
        return "\n".join(lines)
