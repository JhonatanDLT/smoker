"""Write generated rows as a SQL script for the active dialect.

This is the no-database path: load a schema from a dump, generate rows, and
write a file that can be applied with ``psql`` or ``sqlcmd``. The dialect owns
the statements that differ between engines (transaction boundaries, truncate,
identity handling, sequence reseed).
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path
from typing import Any

from ..core.dialect import SqlDialect
from ..core.ir import Table
from .postgres.serialization import copy_text


class SqlFileWriter:
    """RowWriter adapter that emits a SQL script instead of touching a database."""

    def __init__(
        self,
        path: str | Path,
        dialect: SqlDialect,
        truncate: bool = False,
        statement_rows: int = 100,
    ) -> None:
        self.path = Path(path)
        self.dialect = dialect
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.handle = self.path.open("w", encoding="utf-8")
        self.truncate_first = truncate
        self.statement_rows = max(1, statement_rows)
        self._closed = False
        self._write("-- Generated by pgproof. Synthetic data only.")
        for statement in self.dialect.script_begin():
            self._write(statement)

    def _write(self, text: str) -> None:
        if self._closed:
            raise RuntimeError("the SQL writer is closed")
        self.handle.write(text + "\n")

    def truncate(self, tables: list[Table]) -> None:
        if not self.truncate_first or not tables:
            return
        for statement in self.dialect.script_truncate(tables):
            self._write(statement)

    def write(
        self,
        table: Table,
        rows: Iterable[tuple[Any, ...]],
        method: str = "insert",
        hasher: Any = None,
    ) -> int:
        columns = table.writable_columns
        if not columns:
            return 0
        qualified = self.dialect.quote_qualified(table.schema, table.name)
        column_list = ", ".join(
            self.dialect.quote_ident(column.name) for column in columns
        )
        header = f"INSERT INTO {qualified} ({column_list}) VALUES"
        for statement in self.dialect.script_before_insert(table):
            self._write(statement)
        batch: list[str] = []
        count = 0
        for row in rows:
            batch.append(
                "(" + ", ".join(self.dialect.literal(value) for value in row) + ")"
            )
            if hasher is not None:
                line = "\t".join(copy_text(value) for value in row) + "\n"
                hasher.update(line.encode("utf-8"))
            count += 1
            if len(batch) >= self.statement_rows:
                self._write(header + "\n  " + ",\n  ".join(batch) + ";")
                batch = []
        if batch:
            self._write(header + "\n  " + ",\n  ".join(batch) + ";")
        for statement in self.dialect.script_after_insert(table):
            self._write(statement)
        return count

    def reset_sequences(self, tables: list[Table]) -> None:
        for statement in self.dialect.script_reset_sequences(tables):
            self._write(statement)

    def commit(self) -> None:
        for statement in self.dialect.script_commit():
            self._write(statement)
        self.handle.flush()

    def rollback(self) -> None:
        for statement in self.dialect.script_rollback():
            self._write(statement)
        self.handle.flush()

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        self.handle.close()


SqlScriptWriter = SqlFileWriter

__all__ = ["SqlFileWriter", "SqlScriptWriter"]
