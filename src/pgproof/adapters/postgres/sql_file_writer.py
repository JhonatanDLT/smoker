"""Write generated rows as a PostgreSQL INSERT script.

This is the no-database path: load a schema from a dump, generate rows, and
write a file that can be applied with ``psql -f data.sql``. The file contains
``BEGIN``/``COMMIT``, optional ``TRUNCATE`` statements, batched ``INSERT``
statements and ``setval`` calls for identity/serial columns.
"""

from __future__ import annotations

from collections.abc import Iterable
from pathlib import Path
from typing import Any

from ...core.ir import Table, quote_ident, quote_qualified
from .serialization import copy_text, sql_literal

TRUNCATE_BATCH_SIZE = 100


class SqlFileWriter:
    """RowWriter adapter that emits SQL instead of touching a connection."""

    def __init__(
        self,
        path: str | Path,
        truncate: bool = False,
        statement_rows: int = 100,
    ) -> None:
        self.path = Path(path)
        self.path.parent.mkdir(parents=True, exist_ok=True)
        self.handle = self.path.open("w", encoding="utf-8")
        self.truncate_first = truncate
        self.statement_rows = max(1, statement_rows)
        self._closed = False
        self._write("-- Generated by pgproof. Synthetic data only.")
        self._write("BEGIN;")

    def _write(self, text: str) -> None:
        if self._closed:
            raise RuntimeError("the SQL writer is closed")
        self.handle.write(text + "\n")

    def truncate(self, tables: list[Table]) -> None:
        if not self.truncate_first or not tables:
            return
        for start in range(0, len(tables), TRUNCATE_BATCH_SIZE):
            batch = tables[start : start + TRUNCATE_BATCH_SIZE]
            targets = ", ".join(
                quote_qualified(table.schema, table.name) for table in batch
            )
            self._write(f"TRUNCATE {targets} CASCADE;")

    def write(
        self,
        table: Table,
        rows: Iterable[tuple[Any, ...]],
        method: str = "insert",
        hasher: Any = None,
    ) -> int:
        columns = table.writable_columns
        if not columns:
            return 0
        qualified = quote_qualified(table.schema, table.name)
        column_list = ", ".join(quote_ident(column.name) for column in columns)
        header = f"INSERT INTO {qualified} ({column_list}) VALUES"
        batch: list[str] = []
        count = 0
        for row in rows:
            batch.append(
                "(" + ", ".join(sql_literal(value) for value in row) + ")"
            )
            if hasher is not None:
                line = "\t".join(copy_text(value) for value in row) + "\n"
                hasher.update(line.encode("utf-8"))
            count += 1
            if len(batch) >= self.statement_rows:
                self._write(header + "\n  " + ",\n  ".join(batch) + ";")
                batch = []
        if batch:
            self._write(header + "\n  " + ",\n  ".join(batch) + ";")
        return count

    def reset_sequences(self, tables: list[Table]) -> None:
        for table in tables:
            for column in table.columns:
                if not (
                    column.identity
                    or (column.default or "").startswith("nextval")
                ):
                    continue
                relation = (
                    f"{quote_ident(table.schema)}.{quote_ident(table.name)}"
                ).replace("'", "''")
                qualified = quote_qualified(table.schema, table.name)
                name = quote_ident(column.name)
                self._write(
                    "SELECT setval("
                    f"pg_get_serial_sequence('{relation}', '{column.name}'), "
                    f"COALESCE((SELECT max({name}) FROM {qualified}), 1), "
                    f"(SELECT count(*) > 0 FROM {qualified})"
                    ");"
                )

    def commit(self) -> None:
        self._write("COMMIT;")
        self.handle.flush()

    def rollback(self) -> None:
        self._write("ROLLBACK;")
        self.handle.flush()

    def close(self) -> None:
        if self._closed:
            return
        self._closed = True
        self.handle.close()


__all__ = ["SqlFileWriter"]
